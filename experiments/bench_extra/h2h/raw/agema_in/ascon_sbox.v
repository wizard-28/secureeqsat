module ascon_sbox (clk, rst, din, dout);
  (* AGEMA = "clock" *) input clk;
  (* AGEMA = "reset" *) input rst;
  (* AGEMA = "secure" *) input [4:0] din;
  output [4:0] dout;
  wire n0 = din[0] ^ din[4];
  wire n1 = ~din[1];
  wire n2 = din[2] ^ din[1];
  wire n3 = n1 & n2;
  wire n4 = n0 ^ n3;
  wire n5 = din[4] ^ din[3];
  wire n6 = ~n0;
  wire n7 = n6 & din[1];
  wire n8 = n5 ^ n7;
  wire n9 = n4 ^ n8;
  wire n10 = ~n2;
  wire n11 = n10 & din[3];
  wire n12 = din[1] ^ n11;
  wire n13 = n12 ^ n4;
  wire n14 = ~din[3];
  wire n15 = n14 & n5;
  wire n16 = n2 ^ n15;
  wire n17 = ~n16;
  wire n18 = ~n5;
  wire n19 = n18 & n0;
  wire n20 = din[3] ^ n19;
  wire n21 = n20 ^ n16;
  assign dout[0] = n9;
  assign dout[1] = n13;
  assign dout[2] = n17;
  assign dout[3] = n21;
  assign dout[4] = n8;
endmodule
